import { jsPDF } from "jspdf";
import { Document, Packer, Paragraph, TextRun } from "docx";

export interface CoverLetterExportData {
  text: string;
  company?: string;
  jobTitle?: string;
  subjectLine?: string;
  recipient?: string;
}

function sanitizeFilename(company?: string, jobTitle?: string, ext: "pdf" | "docx" = "pdf"): string {
  const c = (company || "Company").trim().replace(/[^a-zA-Z0-9_-]/g, "_");
  const r = (jobTitle || "Role").trim().replace(/[^a-zA-Z0-9_-]/g, "_");
  return `Cover_Letter_${c}_${r}.${ext}`;
}

/**
 * Exports formatted cover letter as an ATS-friendly, clean vector PDF.
 */
export async function exportCoverLetterPDF(data: CoverLetterExportData): Promise<void> {
  const doc = new jsPDF({
    unit: "pt",
    format: "letter",
  });

  const margin = 54; // 0.75 inch margin
  const pageWidth = 612;
  const pageHeight = 792;
  const contentWidth = pageWidth - margin * 2;
  let currentY = margin + 10;

  doc.setTextColor(30, 41, 59); // Slate-800

  // Optional top Subject Line if not already starting with subject
  const paragraphs = data.text
    .split(/\n+/)
    .map((p) => p.trim())
    .filter(Boolean);

  for (const para of paragraphs) {
    const isSubject =
      para.toLowerCase().startsWith("subject:") ||
      para.toLowerCase().startsWith("re:") ||
      para.toLowerCase().startsWith("regarding:");

    if (isSubject) {
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11.5);
    } else {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(11);
    }

    const lines = doc.splitTextToSize(para, contentWidth);
    const lineHeight = 16;
    const blockHeight = lines.length * lineHeight;

    // Check if paragraph fits on current page
    if (currentY + blockHeight > pageHeight - margin) {
      doc.addPage();
      currentY = margin + 10;
    }

    doc.text(lines, margin, currentY);
    currentY += blockHeight + 14; // Paragraph gap
  }

  const filename = sanitizeFilename(data.company, data.jobTitle, "pdf");
  doc.save(filename);
}

/**
 * Exports formatted cover letter as a Microsoft Word (.docx) document.
 */
export async function exportCoverLetterDOCX(data: CoverLetterExportData): Promise<void> {
  const paragraphs = data.text
    .split(/\n+/)
    .map((p) => p.trim())
    .filter(Boolean);

  const docParagraphs = paragraphs.map((para) => {
    const isSubject =
      para.toLowerCase().startsWith("subject:") ||
      para.toLowerCase().startsWith("re:") ||
      para.toLowerCase().startsWith("regarding:");

    return new Paragraph({
      spacing: {
        after: 220, // ~11pt gap after paragraph
        line: 280, // 1.2 line spacing
      },
      children: [
        new TextRun({
          text: para,
          font: "Calibri",
          size: 22, // 11pt (22 half-points)
          bold: isSubject,
          color: "1E293B",
        }),
      ],
    });
  });

  const doc = new Document({
    title: `Cover Letter - ${data.jobTitle || "Role"} at ${data.company || "Company"}`,
    description: "Generated by Resumo Career Suite",
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: 1440, // 1 inch
              bottom: 1440,
              left: 1440,
              right: 1440,
            },
          },
        },
        children: docParagraphs,
      },
    ],
  });

  const blob = await Packer.toBlob(doc);
  const filename = sanitizeFilename(data.company, data.jobTitle, "docx");

  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
